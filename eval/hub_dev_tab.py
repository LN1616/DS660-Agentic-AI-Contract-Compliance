"""Put the harness-development record (eval.versions_html) into the presentation hub as its own tab.

The tab is §4, right after System design (moved there 22 Nov at the user's request); a first insert goes before the
user-manual tab. Re-running replaces it in place.
The hub's old one-run version table in the summary tab is replaced by a pointer to this tab (one home per number).
Usage:  python -m eval.hub_dev_tab ../01-Presentation-Hub.html
"""
import re
import sys
from pathlib import Path

from eval.versions_html import build

START, END = "<!-- ============ TAB HARNESS DEV", "<!-- ============ /TAB HARNESS DEV -->"
POINTER = """<div class="fig" id="fig-versions">
    <div class="fig-title"><h3>วิวัฒนาการของระบบ: แต่ละเวอร์ชันเปลี่ยน harness อะไร และผลเปลี่ยนอย่างไร</h3></div>
    <p class="note">ย้ายไปแท็บ <b>พัฒนา harness</b> แล้ว: ทุกเวอร์ชัน (SC1–SC2, V1 ขึ้นไป) รัน 3 รอบต่อเวอร์ชันด้วยชุดทดสอบเดียวกัน พร้อม flow ปัญหาที่พบ ทางแก้ และผลที่วัดได้ <button type="button" class="linkish" data-tab="harness">ไปแท็บพัฒนา harness →</button></p>
  </div>
"""


def tab_html() -> str:
    body = build().replace('id="fig-', 'id="dev-')  # hub JS adds a "back to flows" button to every fig-* figure
    return f"""{START} (generated by eval/hub_dev_tab.py) ============ -->
<section class="panel" id="harness" data-tab="4" data-name="พัฒนา harness" hidden>
  <div class="head">
    <div class="eyebrow">§4 · Harness development</div>
    <h2>พัฒนา harness: แต่ละเวอร์ชันแก้อะไร และผลเปลี่ยนอย่างไร</h2>
    <p class="lead">ระบบพัฒนาเป็นขั้น ทุกขั้นเริ่มจากจุดอ่อนที่วัดได้ในเวอร์ชันก่อน แก้ harness ทีละเรื่อง แล้ววัดซ้ำด้วยชุดทดสอบเดิม 3 รอบ
    เพื่อแยกผลของการแก้ออกจากความแปรปรวนระหว่างรอบ · กรอบเขียว = ขั้นที่เพิ่ม · กรอบส้ม = ขั้นที่แก้ · กรอบเส้นประ = แผนที่ยังไม่ได้สร้าง</p>
  </div>
  {body}
</section>
{END}
"""


def main(path: str):
    p = Path(path)
    s = p.read_text(encoding="utf-8")
    if START in s:
        a, b = s.index(START), s.index(END) + len(END)
        s = s[:a] + tab_html().rstrip("\n") + s[b:]
    else:
        at = s.index('<section class="panel" id="manual"')
        s = s[:at] + tab_html() + "\n" + s[at:]
    old = re.search(r'<div class="fig" id="fig-versions">.*?\n  </div>\n', s, re.S)
    if old and "ย้ายไปแท็บ" not in old.group(0):
        s = s[:old.start()] + POINTER + s[old.end():]
    if "section.panel[hidden]" not in s:
        raise SystemExit("hub lost its [hidden] rule")
    p.write_text(s, encoding="utf-8")
    print(f"hub updated: {p}")


if __name__ == "__main__":
    main(sys.argv[1])
